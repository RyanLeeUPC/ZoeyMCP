#!/bin/sh
# Writes examples/derived-image/requirements.txt for a derived image built on OFFICIAL:
#   1. builds the example toolkits' wheel, outside any image, into examples/toolkits/dist;
#   2. copies zoeymcp-constraints.txt out of OFFICIAL;
#   3. compiles requirements.in against it, with hashes, so no toolkit dependency can move a
#      gateway dependency;
#   4. appends the wheel with the hash of the file just built.
# The wheel and requirements.txt are always made together: a rebuilt wheel gets a new hash.
# Usage: examples/derived-image/lock.sh OFFICIAL
set -eu

official="${1:?usage: lock.sh OFFICIAL_IMAGE}"
here="$(cd "$(dirname "$0")" && pwd)"
toolkits="$(cd "$here/../toolkits" && pwd)"
work="$(mktemp -d)"
cid=""
cleanup() {
    [ -z "$cid" ] || docker rm "$cid" >/dev/null 2>&1 || true
    rm -rf "$work"
}
trap cleanup EXIT

rm -rf "$toolkits/dist"
uv build --wheel --out-dir "$toolkits/dist" "$toolkits"
set -- "$toolkits"/dist/*.whl
[ "$#" -eq 1 ] && [ -f "$1" ] || { echo "lock.sh: expected one wheel in $toolkits/dist" >&2; exit 1; }
wheel="$1"

cid="$(docker create "$official")"
docker cp "$cid:/opt/zoeymcp-gateway/zoeymcp-constraints.txt" "$work/constraints.txt"

uv pip compile "$here/requirements.in" --constraint "$work/constraints.txt" \
    --generate-hashes --python-version 3.13 --python-platform linux --no-header \
    --quiet --output-file "$work/dependencies.txt"

if command -v sha256sum >/dev/null 2>&1; then
    digest="$(sha256sum "$wheel" | cut -d' ' -f1)"
else
    digest="$(shasum -a 256 "$wheel" | cut -d' ' -f1)"
fi
{
    echo "# Generated by lock.sh from requirements.in and $(basename "$wheel"); never committed."
    grep -v '^#' "$work/dependencies.txt" || true
    echo "example-toolkits @ file:///build/dist/$(basename "$wheel") --hash=sha256:$digest"
} > "$here/requirements.txt"
echo "wrote $here/requirements.txt"
