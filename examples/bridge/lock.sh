#!/bin/sh
# Writes examples/bridge/requirements.lock for the bridge example's image:
#   1. builds the example server's wheel, outside any image, into examples/bridge/server/dist;
#   2. writes the wheel, with the hash of the file just built, as the whole lock.
# The example server needs only the standard library. A server with dependencies compiles them
# here too, with hashes and wheels only (uv pip compile --generate-hashes --only-binary :all:),
# and a server published only as an sdist is built into a wheel elsewhere and locked by hash.
# The wheel and requirements.lock are always made together: a rebuilt wheel gets a new hash.
# Usage: examples/bridge/lock.sh
set -eu

here="$(cd "$(dirname "$0")" && pwd)"
server="$here/server"

rm -rf "$server/dist"
uv build --wheel --out-dir "$server/dist" "$server"
set -- "$server"/dist/*.whl
[ "$#" -eq 1 ] && [ -f "$1" ] || { echo "lock.sh: expected one wheel in $server/dist" >&2; exit 1; }
wheel="$1"

if command -v sha256sum >/dev/null 2>&1; then
    digest="$(sha256sum "$wheel" | cut -d' ' -f1)"
else
    digest="$(shasum -a 256 "$wheel" | cut -d' ' -f1)"
fi
{
    echo "# Generated by lock.sh from $(basename "$wheel"); never committed."
    echo "example-fetch-server @ file:///build/dist/$(basename "$wheel") --hash=sha256:$digest"
} > "$here/requirements.lock"
echo "wrote $here/requirements.lock"
